-- =====================================================================
-- Сервис-деск и каталог услуг для преподавателей
-- 01_schema.sql: структура БД (PostgreSQL 18)
--
-- Разбивка таблиц по модулям приложения (многомодульный монолит):
--   auth          : role, department, users, user_role
--   catalog       : service_catalog
--   requests      : audience, request, request_status_history
--   notifications : notification
--
-- Пароли и вход хранятся в Keycloak, поэтому в users нет login и password_hash;
-- users это локальный справочник, связанный с Keycloak через keycloak_id (claim "sub").
-- Время хранится в UTC (timestamptz). Статусы заявки хранятся строкой (enum в Java).
-- Скрипт можно запускать повторно: уже существующие объекты пропускаются.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Служебное: автоматическое обновление updated_at
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
RETURN NEW;
END;
$$;

-- =====================================================================
-- Модуль auth
-- =====================================================================

-- Роли (источник истины по правам: Keycloak; здесь справочник для выборок по роли)
CREATE TABLE IF NOT EXISTS role (
    id        smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_role varchar(50) NOT NULL UNIQUE,
    CONSTRAINT chk_role_name CHECK (name_role IN
        ('TEACHER', 'DEPARTMENT_HEAD', 'DEPARTMENT_STAFF', 'DUTY_OFFICER', 'ADMIN'))
    );
COMMENT ON TABLE role IS 'Справочник ролей; названия совпадают с realm roles в Keycloak';

-- Кафедры. head_user_id (зав. кафедрой) получает внешний ключ после создания users
CREATE TABLE IF NOT EXISTS department (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(255) NOT NULL UNIQUE,
    head_user_id bigint
);
COMMENT ON COLUMN department.head_user_id IS 'Зав. кафедрой: кому приходят заявки на согласование';

-- Пользователи (локальный справочник; вход и пароли в Keycloak)
CREATE TABLE IF NOT EXISTS users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keycloak_id   uuid         NOT NULL UNIQUE,
    first_name    varchar(100) NOT NULL,
    last_name     varchar(100) NOT NULL,
    middle_name   varchar(100),
    department_id bigint REFERENCES department (id),
    is_active     boolean      NOT NULL DEFAULT true,
    created_at    timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON COLUMN users.keycloak_id IS 'Идентификатор пользователя из Keycloak (claim sub)';
COMMENT ON COLUMN users.department_id IS 'Кафедра или подразделение';

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_department_head') THEN
ALTER TABLE department
    ADD CONSTRAINT fk_department_head FOREIGN KEY (head_user_id) REFERENCES users (id);
END IF;
END
$$;

-- Роли пользователя (у человека может быть несколько, например преподаватель и зав. кафедрой)
CREATE TABLE IF NOT EXISTS user_role (
    user_id bigint   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id smallint NOT NULL REFERENCES role (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX IF NOT EXISTS idx_users_department ON users (department_id);
CREATE INDEX IF NOT EXISTS idx_user_role_role   ON user_role (role_id);

-- =====================================================================
-- Модуль catalog
-- =====================================================================

-- Каталог услуг
CREATE TABLE IF NOT EXISTS service_catalog (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(255) NOT NULL UNIQUE,
    description  text,
    sla_hours    integer      NOT NULL,
    is_active    boolean      NOT NULL DEFAULT true,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT chk_service_sla_positive CHECK (sla_hours > 0)
);
COMMENT ON COLUMN service_catalog.sla_hours IS 'Целевой срок выполнения в часах (в заявке превращается в due_at)';
COMMENT ON COLUMN service_catalog.is_active IS 'Деактивация вместо удаления, чтобы не ломать старые заявки';

DROP TRIGGER IF EXISTS trg_service_catalog_updated ON service_catalog;
CREATE TRIGGER trg_service_catalog_updated
    BEFORE UPDATE ON service_catalog
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- =====================================================================
-- Модуль requests
-- =====================================================================

-- Кабинеты (аудитории)
CREATE TABLE IF NOT EXISTS audience (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(20) NOT NULL UNIQUE
);

-- Заявки
CREATE TABLE IF NOT EXISTS request (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint      NOT NULL REFERENCES users (id),
    audience_id   bigint      NOT NULL REFERENCES audience (id),
    service_id    bigint      NOT NULL REFERENCES service_catalog (id),
    department_id bigint      NOT NULL REFERENCES department (id),
    status        varchar(30) NOT NULL DEFAULT 'PENDING_HEAD',
    description   text,
    comment       text,
    approver_id   bigint REFERENCES users (id),
    confirmed_by  bigint REFERENCES users (id),
    executor_id   bigint REFERENCES users (id),
    reject_reason text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    due_at        timestamptz NOT NULL,
    completed_at  timestamptz,

    CONSTRAINT chk_request_status CHECK (status IN (
        'PENDING_HEAD', 'PENDING_DEPARTMENT', 'ASSIGNED', 'IN_PROGRESS', 'DONE',
        'REJECTED_BY_HEAD', 'REJECTED_BY_DEPARTMENT', 'CANCELLED')),

    CONSTRAINT chk_request_reject_reason CHECK (
        status NOT IN ('REJECTED_BY_HEAD', 'REJECTED_BY_DEPARTMENT')
        OR (reject_reason IS NOT NULL AND length(btrim(reject_reason)) > 0)),

    CONSTRAINT chk_request_executor CHECK (
        status NOT IN ('ASSIGNED', 'IN_PROGRESS', 'DONE') OR executor_id IS NOT NULL),

    CONSTRAINT chk_request_completed CHECK (
        (status = 'DONE') = (completed_at IS NOT NULL)),

    CONSTRAINT chk_request_due CHECK (due_at >= created_at)
);
COMMENT ON COLUMN request.user_id       IS 'Автор заявки';
COMMENT ON COLUMN request.service_id    IS 'Что сломалось / какая услуга нужна';
COMMENT ON COLUMN request.department_id IS 'Снимок кафедры автора на момент создания (для выдачи зав. кафедрой без JOIN с users)';
COMMENT ON COLUMN request.status        IS 'Статус заявки (enum RequestStatus); DONE = выполнена, остальные = не выполнена; переходы контролирует приложение';
COMMENT ON COLUMN request.comment       IS 'Комментарий преподавателя/сотрудника к запросу услуги';
COMMENT ON COLUMN request.approver_id   IS 'Зав. кафедрой, одобривший или отклонивший заявку';
COMMENT ON COLUMN request.confirmed_by  IS 'Сотрудник отдела, подтвердивший заявку и назначивший исполнителя';
COMMENT ON COLUMN request.executor_id   IS 'Дежурный, который выполняет заявку';
COMMENT ON COLUMN request.due_at        IS 'created_at + sla_hours услуги на момент создания (снимок)';
COMMENT ON COLUMN request.completed_at  IS 'Время закрытия; заполнено только у статуса DONE';

DROP TRIGGER IF EXISTS trg_request_updated ON request;
CREATE TRIGGER trg_request_updated
    BEFORE UPDATE ON request
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_request_user        ON request (user_id);
CREATE INDEX IF NOT EXISTS idx_request_executor    ON request (executor_id);
CREATE INDEX IF NOT EXISTS idx_request_service     ON request (service_id);
CREATE INDEX IF NOT EXISTS idx_request_dept_status ON request (department_id, status);
CREATE INDEX IF NOT EXISTS idx_request_status      ON request (status);
CREATE INDEX IF NOT EXISTS idx_request_created_at  ON request (created_at);
-- просрочки: только открытые заявки
CREATE INDEX IF NOT EXISTS idx_request_open_due    ON request (due_at)
    WHERE status IN ('PENDING_HEAD', 'PENDING_DEPARTMENT', 'ASSIGNED', 'IN_PROGRESS');

-- История статусов (нужна для SLA и статистики)
CREATE TABLE IF NOT EXISTS request_status_history (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  bigint      NOT NULL REFERENCES request (id) ON DELETE CASCADE,
    from_status varchar(30),
    to_status   varchar(30) NOT NULL,
    changed_by  bigint      NOT NULL REFERENCES users (id),
    changed_at  timestamptz NOT NULL DEFAULT now(),
    comment     text,
    CONSTRAINT chk_history_from_status CHECK (from_status IS NULL OR from_status IN (
                                              'PENDING_HEAD', 'PENDING_DEPARTMENT', 'ASSIGNED', 'IN_PROGRESS', 'DONE',
                                              'REJECTED_BY_HEAD', 'REJECTED_BY_DEPARTMENT', 'CANCELLED')),
    CONSTRAINT chk_history_to_status CHECK (to_status IN (
                                            'PENDING_HEAD', 'PENDING_DEPARTMENT', 'ASSIGNED', 'IN_PROGRESS', 'DONE',
                                            'REJECTED_BY_HEAD', 'REJECTED_BY_DEPARTMENT', 'CANCELLED'))
    );
COMMENT ON COLUMN request_status_history.from_status IS 'NULL у записи о создании заявки';

CREATE INDEX IF NOT EXISTS idx_history_request    ON request_status_history (request_id, changed_at);
CREATE INDEX IF NOT EXISTS idx_history_changed_by ON request_status_history (changed_by);

-- =====================================================================
-- Модуль notifications
-- =====================================================================

CREATE TABLE IF NOT EXISTS notification (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type       varchar(50)  NOT NULL,
    request_id bigint REFERENCES request (id) ON DELETE CASCADE,
    title      varchar(255) NOT NULL,
    body       text,
    created_at timestamptz  NOT NULL DEFAULT now(),
    read_at    timestamptz
    );
COMMENT ON COLUMN notification.type IS 'Тип события заявки (RequestCreated, RequestApproved и т.д.)';

CREATE INDEX IF NOT EXISTS idx_notification_user_created ON notification (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notification_user_unread  ON notification (user_id, created_at DESC)
    WHERE read_at IS NULL;

COMMIT;