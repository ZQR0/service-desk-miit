ALTER TABLE request
    ADD COLUMN version bigint NOT NULL DEFAULT 0,
    ADD COLUMN deadline_hours_snapshot integer,
    ADD COLUMN due_at timestamptz;

UPDATE request r
SET deadline_hours_snapshot = s.deadline,
    due_at = r.created_at + make_interval(hours => s.deadline)
FROM service_catalog s
WHERE s.id = r.service_id;

ALTER TABLE request
    ALTER COLUMN deadline_hours_snapshot SET NOT NULL,
    ALTER COLUMN due_at SET NOT NULL;

CREATE TABLE request_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES request(id),
    from_status_id smallint REFERENCES request_status(id),
    to_status_id smallint NOT NULL REFERENCES request_status(id),
    changed_by bigint NOT NULL REFERENCES users(id),
    changed_at timestamptz NOT NULL DEFAULT now(),
    reason text
);

CREATE INDEX idx_request_history_request
    ON request_status_history(request_id, changed_at);
CREATE INDEX idx_request_due_at ON request(due_at);
